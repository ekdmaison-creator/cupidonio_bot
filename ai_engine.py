def gender_word(g):
    return g if g in ("мужчина", "женщина") else "человек"


def address_form(g):
    return {"мужчина": "в мужском роде", "женщина": "в женском роде"}.get(g, "нейтрально, без указания рода")


def relationship_duration(meeting_date_str):
    d = parse_date(meeting_date_str or "")
    if not d:
        return {"days": 0, "years": 0, "months": 0, "stage": "неизвестно",
                "description": "длительность не определена"}
    days = (now() - d).days
    stage, desc = STAGES[-1][1], STAGES[-1][2]
    for limit, st, ds in STAGES:
        if days < limit:
            stage, desc = st, ds
            break
    return {"days": days, "years": days // 365, "months": (days % 365) // 30,
            "stage": stage, "description": desc}


def season_name(month):
    if month in (12, 1, 2):
        return "зима"
    if month in (3, 4, 5):
        return "весна"
    if month in (6, 7, 8):
        return "лето"
    return "осень"


def context_block(u, user_id):
    dur = relationship_duration(u["meeting_date"])
    state = u.get("relationship_state") or "отлично"
    n = now()
    lines = [
        f"КТО: {u['name']} ({gender_word(u['user_gender'])}). Партнёр: {u['partner_name']} ({gender_word(u['partner_gender'])}).",
        f"Обращайся к {u['name']} {address_form(u['user_gender'])}. Всё делает {u['name']} для партнёра, а не наоборот.",
        f"История: познакомились — {u['meeting_place']}; увлечения — {u['hobbies']}; любимый фильм/книга — {u['favorite_movie']}; язык любви — {u['love_language']}.",
        f"Вместе: {dur['years']} г. {dur['months']} мес. ({dur['days']} дн.). Стадия: {dur['stage']}. {dur['description']}",
        f"Состояние отношений: {state}. {STATE_HINTS.get(state, STATE_HINTS['отлично'])}",
        f"Сегодня: {WEEKDAYS[n.weekday()]}, {season_name(n.month)}.",
    ]
    if state in ("отдалились", "кризис"):
        lines.append("Увлечения используй МЯГКО и необязывающе, без «романтического вечера».")
    feedback = database.get_recent_feedback(user_id, 3)
    if feedback:
        lines.append("ПОЖЕЛАНИЯ ПОЛЬЗОВАТЕЛЯ (обязательно учти): " + "; ".join(feedback))
    return "\n".join(lines)


async def ask_ai(prompt, temperature=1.0, max_tokens=800):
    resp = await client.chat.completions.create(
        model="deepseek-chat",
        messages=[{"role": "system", "content": SYSTEM}, {"role": "user", "content": prompt}],
        temperature=temperature, max_tokens=max_tokens)
    return clean_markdown((resp.choices[0].message.content or "").strip())


async def generate_task(user_id, mode=None):
    """Возвращает (текст задания, категория) или None."""
    u = database.get_user(user_id)
    if not u:
        return None
    state = u.get("relationship_state") or "отлично"
    cats = STATE_CATEGORIES.get(state, list(CATEGORIES))
    last = database.get_last_category(user_id)
    category = random.choice([c for c in cats if c != last] or cats)

    extra = ""
    if mode in MODES and not (mode == "bold" and state in ("отдалились", "кризис")):
        extra += f"ВАРИАНТ: сделай задание {MODES[mode]}\n"
    recent = database.get_recent_task_titles(user_id, 10)
    if recent:
        extra += "НЕ ПОВТОРЯЙ идеи прошлых заданий: " + "; ".join(recent) + "\n"
    liked = database.get_liked_titles(user_id, 3)
    if liked:
        extra += "Партнёру особенно понравились такие задания (бери стиль, но не копируй): " + "; ".join(liked) + "\n"

    prompt = (
        f"{context_block(u, user_id)}\n\n"
        f"КАТЕГОРИЯ: {category}. {CATEGORIES[category]}\n"
        f"{extra}"
        "Свяжи задание с одним из увлечений пары или языком любви, если это получается естественно.\n\n"
        "ФОРМАТ ОТВЕТА (строго):\n"
        "🎯 Название задания\n\n"
        "Шаг 1. [конкретное действие]\n"
        "Шаг 2. [конкретное действие]\n"
        "Шаг 3. [конкретное действие]\n\n"
        "⏱ Время: [5-15] минут\n\n"
        "Максимум 3 шага, каждый выполним за 2–3 минуты.\n" + RULES
    )
    text = await ask_ai(prompt, 1.0, 700)
    return (text, category) if text else None


